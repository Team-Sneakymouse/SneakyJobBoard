#!/usr/bin/env python3
"""Regenerates src/resources/legacy-item-models.json from the craftengine-resources mapping.

Usage: tools/generate-legacy-item-models.py [path/to/craftengine-resources/resources/base/legacy-item-models.json]

The plugin only needs (carrier, integer custom_model_data) -> item model, to read advert icons that were stored
as integers. Output shape: {"carriers": {"<carrier>": [[min, maxExclusive|null, "<ns:id>"], ...]}}.
Routes with a null upper bound apply to every integer >= min (the last dispatch threshold in the pack).
"""
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    here, "..", "..", "craftengine-resources", "resources", "base", "legacy-item-models.json")
target = os.path.join(here, "..", "src", "resources", "legacy-item-models.json")

with open(source, encoding="utf-8") as handle:
    routes = json.load(handle)["routes"]

carriers = {}
for route in routes:
    if route["residual_custom_model_data"]:
        continue  # routes that still need extra components cannot be expressed as a plain item model
    carrier = route["carrier"].removeprefix("minecraft:")
    interval = route["interval"]
    carriers.setdefault(carrier, []).append([interval["min"], interval["max_exclusive"], route["item_model"]])

for entries in carriers.values():
    entries.sort(key=lambda entry: entry[0])

with open(target, "w", encoding="utf-8", newline="\n") as handle:
    handle.write('{\n"source": "craftengine-resources/resources/base/legacy-item-models.json (generated by tools/generate-legacy-item-models.py)",\n"carriers": {\n')
    handle.write(",\n".join(
        '%s: %s' % (json.dumps(name), json.dumps(entries, separators=(",", ":")))
        for name, entries in sorted(carriers.items())))
    handle.write("\n}\n}\n")
print("wrote", target, sum(len(v) for v in carriers.values()), "routes")
